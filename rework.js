const LOCAL_PREVIEW = ['localhost', '127.0.0.1', '[::1]', ''].includes(location.hostname) || /^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.)/.test(location.hostname) || location.hostname.endsWith('.local');
const FORM_ENDPOINT = 'https://formspree.io/f/xyknpdjv';
const STORAGE_KEY = 'cv_rework_locale';
let locale = 'es';
let sending = false;
let statusKey = '';
let statusState = '';
let captchaId = null;
let captchaLoading = false;
const form = document.querySelector('#project-form');
const selector = document.querySelector('#language');
const status = document.querySelector('#form-status');
const submitText = form.querySelector('[data-copy="submit"]');

function setStatus(key, state = '') {
  statusKey = key;
  statusState = state;
  status.textContent = key ? COPY[locale][key] : '';
  status.dataset.state = state;
}
function renderLines(node, key, copy) {
  node.replaceChildren(...copy[key].map((line, index) => {
    const span = document.createElement('span');
    if (key === 'servicesTitle' && index === copy[key].length - 1) {
      const mark = document.createElement('mark');
      mark.textContent = line;
      span.append(mark);
    } else if (key === 'contactTitle' && line.includes(copy.contactHighlight)) {
      const start = line.indexOf(copy.contactHighlight);
      span.append(document.createTextNode(line.slice(0, start)));
      const mark = document.createElement('mark');
      mark.textContent = copy.contactHighlight;
      span.append(mark, document.createTextNode(line.slice(start + copy.contactHighlight.length)));
    } else if (line.endsWith('.') || line.endsWith('。')) {
      span.append(document.createTextNode(line.slice(0, -1)));
      const dot = document.createElement('span');
      dot.className = 'dot';
      dot.textContent = line.slice(-1);
      span.append(dot);
    } else span.textContent = line;
    return span;
  }));
}
function applyLocale(next) {
  locale = Object.hasOwn(COPY, next) ? next : 'es';
  const copy = COPY[locale];
  window.creativividCopy = copy;
  document.documentElement.lang = locale;
  document.title = copy.title;
  document.querySelector('meta[name="description"]').content = copy.description;
  selector.value = locale;
  document.querySelectorAll('[data-copy]').forEach(node => { node.textContent = copy[node.dataset.copy]; });
  document.querySelectorAll('[data-lines]').forEach(node => renderLines(node, node.dataset.lines, copy));
  document.querySelectorAll('[data-label]').forEach(node => node.setAttribute('aria-label', copy[node.dataset.label]));
  document.querySelectorAll('[data-alt]').forEach(node => node.alt = copy[node.dataset.alt]);
  document.querySelectorAll('[data-privacy]').forEach(node => { node.href = `./privacy.html?lang=${locale}`; });
  if (sending) submitText.textContent = copy.sending;
  setStatus(statusKey, statusState);
  document.dispatchEvent(new Event('creativivid:locale'));
  try { localStorage.setItem(STORAGE_KEY, locale); } catch { /* Private browsing may disable storage. */ }
}
let requestedLocale = new URLSearchParams(location.search).get('lang');
if (!requestedLocale) { try { requestedLocale = localStorage.getItem(STORAGE_KEY); } catch { /* Use Spanish by default. */ } }
applyLocale(requestedLocale);
selector.addEventListener('change', () => {
  applyLocale(selector.value);
  const url = new URL(location.href);
  url.searchParams.set('lang', locale);
  history.replaceState(null, '', url);
});
document.querySelector('#year').textContent = new Date().getFullYear();

function loadCaptcha() {
  if (LOCAL_PREVIEW || captchaLoading) return;
  captchaLoading = true;
  window.cvRenderCaptcha = () => {
    captchaId = window.turnstile.render('#captcha', {
      sitekey: '0x4AAAAAACqP0xV6NCSkGF91', theme: 'dark', language: 'auto',
      callback: () => { if (statusKey === 'captcha') setStatus(''); },
      'error-callback': () => { setStatus('captchaError', 'error'); return true; },
      'expired-callback': () => setStatus('captcha', 'error')
    });
  };
  const script = document.createElement('script');
  script.src = 'https://challenges.cloudflare.com/turnstile/v0/api.js?onload=cvRenderCaptcha&render=explicit';
  script.async = true;
  script.onerror = () => setStatus('captchaError', 'error');
  document.head.append(script);
}
if (!LOCAL_PREVIEW) {
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(entries => {
      if (entries.some(entry => entry.isIntersecting)) { loadCaptcha(); observer.disconnect(); }
    }, { rootMargin: '400px' });
    observer.observe(form);
  } else loadCaptcha();
}
form.addEventListener('submit', async event => {
  event.preventDefault();
  if (sending || !form.reportValidity()) return;
  if (LOCAL_PREVIEW) { setStatus('local'); return; }
  loadCaptcha();
  const token = captchaId !== null ? window.turnstile?.getResponse(captchaId) : '';
  if (!token) { setStatus('captcha', 'error'); return; }
  sending = true;
  const button = form.querySelector('button[type="submit"]');
  button.disabled = true;
  submitText.textContent = COPY[locale].sending;
  setStatus('sending');
  const payload = new FormData(form);
  payload.set('contact_email', payload.get('email'));
  payload.set('locale', locale);
  payload.set('source_page', location.href);
  payload.set('consent', 'true');
  payload.set('cf-turnstile-response', token);
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);
  try {
    const response = await fetch(FORM_ENDPOINT, { method: 'POST', headers: { Accept: 'application/json' }, body: payload, signal: controller.signal });
    if (!response.ok) throw new Error('Request failed');
    form.reset();
    setStatus('success', 'success');
  } catch { setStatus('error', 'error'); }
  finally {
    clearTimeout(timer);
    sending = false;
    button.disabled = false;
    submitText.textContent = COPY[locale].submit;
    window.turnstile?.reset(captchaId);
  }
});
